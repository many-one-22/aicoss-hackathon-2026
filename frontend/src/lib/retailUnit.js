/* 제철 시세를 '실제 장 볼 때 사는 단위'로 환산한다.

   [배경] 원본(KAMIS) 소매가격의 기준 수량이 데이터 가공 과정에서 잘려나가
   '100g'→'g', '20kg'→'kg', '20마리'→'마리' 처럼 수량이 빠진 채 저장돼 있다.
   그래서 "건고추 18,159원/100g"(실제로는 1kg 값) 같은 잘못된 표기가 생겼다.

   [해결] 품목별로 [배수, 표시단위, 체감설명(선택)] 을 정의한다.
     - 배수: current × 배수 = 화면에 보여줄 가격
     - 표시단위: 사람들이 실제로 사는 단위 이름
   스펙이 없는 품목은 원본 단위를 그대로 쓴다(추측해서 틀린 값을 보여주지 않기 위해).

   ※ 단위 교정의 근거는 가격대다. 예를 들어 건고추 18,159원은 100g일 수 없고(1kg 1.5~2만원대),
     쌀 41,494원은 1kg이 아니라 20kg 한 포대 가격이다. */

const SPEC = {
  /* ── 수량이 잘려 잘못 표기되던 품목 교정 (가격대로 기준 수량 확인) ── */
  건고추: [1, '1kg'],
  참깨: [1, '1kg'],
  팥: [1, '1kg'],
  녹두: [1, '1kg'],
  콩: [1, '1kg'],
  홍합: [1, '1kg'],
  쌀: [1, '20kg 한 포대'],
  절임배추: [1, '20kg 한 박스'],
  건오징어: [1, '20마리(한 축)'],
  마른오징어: [1, '20마리(한 축)'],

  /* ── 100g 단위 → 실제 사 오는 단위(kg)로 환산 ── */
  감자: [10, '1kg', '5~6개'],
  시금치: [10, '1kg'],

  /* ── kg 단위 채소·과일: 개수 감각만 덧붙임 ── */
  양파: [1, '1kg', '5~6개'],
  당근: [1, '1kg', '6~7개'],
  토마토: [1, '1kg', '약 5개'],
  고구마: [1, '1kg', '4~5개'],
  방울토마토: [1, '1kg', '한 팩'],

  /* ── 잎채소·고추류: 소량 구매가 일반적이라 100g 유지, 체감만 보강 ── */
  풋고추: [1, '100g', '약 10개'],
  붉은고추: [1, '100g', '약 10개'],
  상추: [1, '100g', '10~15장'],
  깻잎: [1, '100g', '약 30장'],

  /* ── 이미 실구매 단위인 품목: 이름만 명확히 ── */
  오이: [1, '10개'],
  전복: [1, '5마리'],
  김: [1, '10장'],
  콩나물: [1, '한 봉'],
};

/* 스펙이 없을 때의 최소 교정 — 수량이 빠진 축약 단위에 기본 수량을 붙인다. */
function fallbackUnit(unit) {
  const map = {
    g: '100g',
    kg: '1kg',
    개: '1개',
    마리: '1마리',
    포기: '1포기',
    봉: '한 봉',
    장: '1장',
  };
  return map[unit] || unit;
}

/* 시세 레코드 → 실구매 단위 표시값. 반환: { price, unit, hint } */
export function retailOf(item, current, unit) {
  const spec = SPEC[item];
  if (!spec) return { price: Math.round(current), unit: fallbackUnit(unit), hint: null };
  const [mult, label, hint = null] = spec;
  return { price: Math.round(current * mult), unit: label, hint };
}
